import assert from 'node:assert/strict';
import { ENGINES } from '../web/minigame-redesign.js';
const events=[];
const game=ENGINES.shootout(null,{seed:123},{hit(){events.push('hit')},miss(){events.push('miss')},finish(){}});
assert.equal(game.getState().phase,'attack');
game.update(.5);
const moving=game.getState();
assert.ok(moving.keeperVisual>1.5,'进攻时门将应明显离开中路');
game.onAction('right'); game.onAction('primary');
let result=game.getState();
assert.equal(result.keeperLane,Math.round(moving.keeperVisual),'进攻判定应使用射门时看到的门将位置');
assert.equal(result.goalsFor,Number(result.shotLane!==result.keeperLane));
game.update(1.36);
assert.equal(game.getState().phase,'preview');
const shot=game.getState().shotLane;
game.update(1.31);
assert.equal(game.getState().phase,'save');
game.onAction(['left','center','right'][shot]);
result=game.getState();
assert.equal(result.keeperLane,shot,'防守结果应记录选择的扑救方向');
assert.equal(result.saves,1);
game.update(.35);
assert.ok(Math.abs(game.getState().keeperVisual-shot)<.05,'门将动画应移动到实际扑救方向');
console.log('点球进攻门将移动、射门判定、防守提示方向和扑救动画状态检查通过');
