import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { randomUUID } from 'node:crypto';
import { createVisitStore } from '../server/visits.js';
import { listPlaces } from '../server/places.js';

const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'cc-visits-'));
const file = path.join(dir, 'visits.json');
const places = listPlaces();
assert.equal(places.length, 16);
assert.equal(new Set(places.map(p => p.id)).size, 16);
for (const p of places) assert.ok(p.desc && p.highlights.length >= 3 && p.architecture && p.sourceUrl);
const store = await createVisitStore(file, places);
assert.equal(store.snapshot().total, 0);
let broadcasts = 0;
store.subscribe(() => broadcasts++);
const id = randomUUID();
await Promise.all(Array.from({ length: 20 }, () => store.record({ placeId: 'palace', eventId: id })));
assert.equal(store.snapshot().total, 1, '相同事件重试只记一次');
await Promise.all(Array.from({ length: 25 }, () => store.record({ placeId: 'wuhuan', eventId: randomUUID() })));
assert.equal(store.snapshot().total, 26, '并发写入不丢记录');
assert.equal(store.snapshot().todayTotal, 26);
assert.equal(broadcasts, 26, '落盘成功后推送一次');
await assert.rejects(store.record({ placeId: 'unknown', eventId: randomUUID() }));
await assert.rejects(store.record({ placeId: 'film', eventId: id }));
const restored = await createVisitStore(file, places);
assert.equal(restored.snapshot().total, 26, '重启后恢复记录');
await restored.record({ placeId: 'palace', eventId: id });
assert.equal(restored.snapshot().total, 26, '重启后仍然幂等');
await fs.unlink(file);await fs.rmdir(dir);
console.log('通过：16 个地点内容、并发计数、重试去重、推送与重启恢复。测试数据使用临时文件。');
